import chalk from 'chalk';
import * as path from 'node:path';
import {fetchDesign} from '../fetcher';
import {parseCss} from '../css-parser';
import {
	tokensToJson,
	tokensToCssVars,
	tokensToScss,
	tokensTailwindConfig,
	writeFile,
} from '../output';

function generateReadme(domain: string): string {
	return `# Design System — ${domain}

Generated by [designlang](https://github.com/remotion-dev/remotion).

## Files

| File | Description |
|------|-------------|
| \`tokens.json\` | All design tokens as JSON |
| \`tokens.css\` | CSS custom properties (\`:root\` block) |
| \`tokens.scss\` | SCSS variables |
| \`tailwind.config.js\` | Tailwind CSS configuration extension |
| \`typography.css\` | Typography utility classes |
| \`components/\` | Basic component styles |

## Usage

### CSS Custom Properties
\`\`\`html
<link rel="stylesheet" href="tokens.css">
\`\`\`

### SCSS
\`\`\`scss
@import 'tokens';
\`\`\`

### Tailwind
Copy \`tailwind.config.js\` to your project root and merge with your existing config.
`;
}

function generateTypographyCss(domain: string, fontFamilies: string[], fontSizes: string[]): string {
	const primaryFont = fontFamilies[0] ?? 'system-ui';
	const secondaryFont = fontFamilies[1] ?? fontFamilies[0] ?? 'system-ui';
	const sizes = fontSizes.slice(0, 8);

	return `/* Typography — ${domain} */

body {
  font-family: ${JSON.stringify(primaryFont)}, system-ui, -apple-system, sans-serif;
  line-height: 1.5;
}

h1, h2, h3, h4, h5, h6 {
  font-family: ${JSON.stringify(secondaryFont)}, system-ui, -apple-system, sans-serif;
  line-height: 1.2;
  font-weight: 700;
}

${sizes.map((s, i) => `.text-${i + 1} { font-size: ${s}; }`).join('\n')}
`;
}

