export async function runPack(targetUrl: string): Promise<void> {
	console.log(chalk.cyan(`Fetching ${targetUrl}…`));
	const design = await fetchDesign(targetUrl);
	console.log(chalk.cyan('Extracting design tokens…'));
	const tokens = parseCss(design.css, design.baseUrl, design.domain);

	const outDir = `designlang-pack-${tokens.domain}`;
	const files: Array<[string, string]> = [
		[path.join(outDir, 'tokens.json'), tokensToJson(tokens)],
		[path.join(outDir, 'tokens.css'), tokensToCssVars(tokens)],
		[path.join(outDir, 'tokens.scss'), tokensToScss(tokens)],
		[path.join(outDir, 'tailwind.config.js'), tokensTailwindConfig(tokens)],
		[
			path.join(outDir, 'typography.css'),
			generateTypographyCss(
				tokens.domain,
				tokens.typography.fontFamilies,
				tokens.typography.fontSizes,
			),
		],
		[
			path.join(outDir, 'components', 'base.css'),
			generateComponentsCss(tokens.domain),
		],
		[path.join(outDir, 'README.md'), generateReadme(tokens.domain)],
	];

	for (const [filePath, content] of files) {
		writeFile(filePath, content);
	}

	console.log(
		chalk.green(`\n✓ Design system packed for ${tokens.domain}`),
	);
	console.log(
		chalk.dim(
			`  ${files.length} files written`,
		),
	);
	console.log(chalk.bold(`\n📦 Output: ./${outDir}/`));
	console.log(chalk.dim('  tokens.json  tokens.css  tokens.scss  tailwind.config.js'));
	console.log(chalk.dim('  typography.css  components/base.css  README.md'));
}
